"""Phase 8 - BEAMER Python job-script generator (Route B helper).

Generates a BEAMERpy script that imports the snapped GDSII written by ``export_route_b`` and exports a JEOL
v30 file with BEAMER's ``export_v30`` command.  Parameter NAMES, TYPES and allowed enumerators come from the
GenISys BEAMER v4.6.6 manual, chapter 11 "Python Scripting" (11.4.8.15 export_v30, 11.4.14 heal, 11.4.10 fda,
11.4.15.8 import_gds, 11.4.1 number of cores).  The manual does NOT document the .v30 binary records and says that
JEOL format details are shipped only to JEOL-licensed users (manual section 4.2.4.8-4.2.4.10), so nothing here
writes or interprets binary data.  Values whose meaning is facility-specific are flagged TODO-VERIFY.

IMPORTANT: BEAMER 4.6.6 documents Python 2.6.5 (Windows) / 2.4.3 (Linux).  The generated script therefore
uses only syntax valid in Python 2.6: ``%`` formatting, no f-strings, no ``str.format`` auto-numbering.
"""
from __future__ import annotations
from typing import Dict, List, Sequence, Tuple, TYPE_CHECKING

if TYPE_CHECKING:  # pragma: no cover
    from .jeol import JeolOptions

# Enumerator values taken verbatim from the manual (11.4.8.15 export_v30 parameter table / 11.4.12 fracture).
FRACTURE_MODES = ("Conventional", "LRFT", "Curved")
# Manual 4.2.4.9 / 4.2.4.10 list these machines; the exact MachineType STRING is only shown for the 9300FS 100 kV
# example ('JBX-9300FS (100kV)') in the manual, so the others are TODO-VERIFY against the BEAMER dialog.
V52_MACHINES = ("JBX-9000MV(50kV)", "JBX-9300FS(50kV)", "JBX-9300FS(100kV)", "JBX-6300SA", "JBX-6300FS/2", "JBX-5500")
MANUAL_EXAMPLE_MACHINE = "JBX-9300FS (100kV)"


def _num(v: float) -> str:
    """Six-decimal string, the style used by the manual's export_v30 example ('1000.000000')."""
    return "%.6f" % float(v)


def _int_str(v: float) -> str:
    return str(int(round(v))) if abs(v - round(v)) < 1e-9 else repr(float(v))


def _bool(v: bool) -> str:
    # export_v30 example in the manual passes booleans as the strings 'true' / 'false'.
    return "'true'" if v else "'false'"


def dose_layer_list(keys: Sequence[Tuple[int, int]], factor_of) -> List[Tuple[str, float]]:
    """[(layer(datatype) name, relative dose)] for entries whose factor differs from 1.0 (manual 3.13 naming)."""
    return [("%d(%d)" % (l, d), float(factor_of(l, d))) for l, d in keys if abs(factor_of(l, d) - 1.0) > 1e-12]


def build_beamer_script(name: str, opts: "JeolOptions", keys: Sequence[Tuple[int, int]] = (),
                        gds_name: str = "", heal: bool = True) -> str:
    """Return the text of a Python-2.6-compatible BEAMERpy script. ``keys`` are the (layer, datatype) pairs present."""
    if opts.fracture_mode not in FRACTURE_MODES:
        raise ValueError("fracture_mode must be one of %s" % (FRACTURE_MODES,))
    gds = gds_name or ("%s.gds" % name)
    F, S = opts.fields.field_size / 1e3, opts.fields.subfield_size
    ov = opts.fields.overlap / 1e3
    eos_known = str(opts.eos_mode).strip().isdigit()
    lines: List[str] = [
        "# -*- coding: utf-8 -*-",
        "# BEAMERpy job script for %s -> %s.v30  (generated by LithoMask Phase 8, Route B)" % (name, name),
        "# Syntax is Python 2.6 compatible on purpose (BEAMER 4.6.6 manual, ch. 11: Windows needs Python 2.6.5).",
        "# Parameter names follow the BEAMER 4.6.6 manual (export_v30, heal, fda, import_gds).",
        "# TODO-VERIFY lines depend on your facility / BEAMER version; check them in the BEAMER Export (JEOL v30) dialog.",
        "# Run with the Python that ships with / matches your BEAMER install:   python %s_beamer_job.py" % name,
        "import os",
        "import sys",
        "",
        "# --- adjust to your installation (manual 11.2: sys.path.append(<BEAMER>/bin) on Windows, <BEAMER>/lib on Linux)",
        "BEAMER_BIN = os.environ.get('BEAMER_BIN', r'C:/Program Files/GenISys/BEAMER4.6.6/bin')",
        "sys.path.append(BEAMER_BIN)",
        "import BEAMERpy   # for Python 2.4.3 / 2.6.x the manual also names BEAMERpy23 / BEAMERpy26",
        "",
        "HERE = os.path.dirname(os.path.abspath(__file__))",
        "lb = BEAMERpy.GBEAMER()",
        "lb.set_number_of_threads(%d)" % opts.threads,
        "",
        "imp = lb.import_gds({'FileName': os.path.join(HERE, %r)})" % gds,
    ]
    last = "imp"
    if heal:
        lines += [
            "# Overlap removal per layer: a plain heal merges ALL layers onto one target layer (manual 4.2.9.1).",
            "# TODO-VERIFY: PerLayer + '*' keeps layer/datatype on your BEAMER version (inspect result in VIEWER).",
            "healed = lb.heal(imp, {'ProcessingMode': 'OverlapRemoval', 'LayerAssignment': 'PerLayer',"
            " 'SelectedLayerSet': '*'})",
        ]
        last = "healed"
    dl = dose_layer_list(keys, opts.dose.factor_of)
    if dl:
        items = ", ".join("[%r, %s]" % (n, _num(f)) for n, f in dl)
        lines += [
            "# Relative dose per layer(datatype) -> BEAMER FDA (manual 4.3.5 / 11.4.10).",
            "dosed = lb.fda(%s, {'AssignmentType': 'Assign Value', 'LayerDoseList': [%s]})" % (last, items),
        ]
        last = "dosed"
    p: List[str] = [
        "'FileName': os.path.join(HERE, %r)" % ("%s.v30" % name),
        "'ExtentMode': 'Default'",
        "'MachineType': %r" % opts.machine,
        "'Resolution': %r" % _int_str(opts.pattern_unit),
        "'MemorySize': %r" % str(opts.memory_size),
        "'EOSMode': %r" % str(opts.eos_mode if eos_known else "1"),
        "'FieldSizeX': %r" % _num(F),
        "'FieldSizeY': %r" % _num(F),
        "'FieldOverlapX': %r" % _num(ov),
        "'FieldOverlapY': %r" % _num(ov),
    ]
    if S:
        p += ["'SubfieldSizeX': %r" % _num(S / 1e3), "'SubfieldSizeY': %r" % _num(S / 1e3)]
    p += [
        "'CenterToField': %s" % _bool(opts.center_to_field),
        "'NormalizeDose': %s" % _bool(opts.normalize_dose),
        "'PreserveDoseRange': %s" % _bool(opts.preserve_dose_range),
        "'UseCompaction': %s" % _bool(opts.use_compaction),
        "'CorrectLines': %s" % _bool(opts.correct_lines),
        "'ReservedSingleLineClasses': %r" % str(opts.reserved_single_line_classes),
        "'FractureMode': %r" % opts.fracture_mode,
    ]
    lines += [
        "",
        "# export_v30 (manual 11.4.8.15).  Unit of 'Resolution' = TODO-VERIFY (manual example uses '1' for a",
        "# JBX-9300FS 100 kV, matching a 1 nm Pattern Unit); the manual types it as an integer string.",
        "# 'MachineType' must match BEAMER's list exactly; only '%s' is shown in the manual." % MANUAL_EXAMPLE_MACHINE,
        "# 'EOSMode', 'MemorySize' %s are facility specific: TODO-VERIFY." % ("" if eos_known else "(EOSMode defaulted to '1')"),
        "exp = lb.export_v30(%s, {" % last,
    ]
    lines += ["    " + x + ("," if i < len(p) - 1 else "") for i, x in enumerate(p)]
    lines += [
        "})",
        "print('Wrote %s' % os.path.join(HERE, " + repr("%s.v30" % name) + "))",
        "",
    ]
    return "\n".join(lines)
